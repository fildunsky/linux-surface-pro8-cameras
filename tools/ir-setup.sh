#!/bin/bash
# Собрать media-граф ИК-камеры VD55G0 и выставить формат.
#
# ГЛАВНОЕ, что стоило недели: формат на ноде захвата обязан быть
# НЕУПАКОВАННЫМ ('Y10 '), а не упакованным ('Y10P').
#
# ISYS выбирает mipi_store_mode по правилу (ipu6-isys-video.c:496):
#     bpp == bpp_packed ? DISCARD_LONG_HEADER (1) : NORMAL (0)
# У Y10P bpp = bpp_packed = 10, у GREY 8 = 8 — оба дают режим 1, и на этом
# железе он не работает: сенсор снимает, но наружу уходит ровно один
# короткий пакет начала кадра. У 'Y10 ' bpp = 16, bpp_packed = 10, режим 0
# — и всё едет: 50 кадр/с, ноль ошибок csi2.
set -u
[ "$(id -u)" = 0 ] || { echo "нужен root" >&2; exit 1; }
W=${W:-644}; H=${H:-604}
M=${M:-/dev/media0}
SENSOR='"vd55g 3-0060"'
CSI='"Intel IPU6 CSI2 5"'
CAP='"Intel IPU6 ISYS Capture 40"'

media-ctl -d "$M" -l "$SENSOR:0 -> $CSI:0[1]" 2>/dev/null
media-ctl -d "$M" -l "$CSI:1 -> $CAP:0[1]" 2>/dev/null || {
  echo "не удалось включить связь $CSI:1 -> $CAP" >&2; exit 1; }
for pad in "$SENSOR:0" "$CSI:0" "$CSI:1"; do
  media-ctl -d "$M" -V "$pad [fmt:Y10_1X10/${W}x${H}]" || {
    echo "не удалось выставить формат на $pad" >&2; exit 1; }
done
# ИК-подсветка. Без неё в комнате со светодиодными лампами кадр почти
# чёрный: такие лампы инфракрасного почти не дают, в отличие от солнца и
# ламп накаливания. Экспозиция при этом упирается в потолок (1796 из
# 1796) и цифровое усиление уходит на x8, а средняя яркость всё равно
# около 16 из 255 — распознать лицо невозможно.
#
# Подсветка висит на GPIO 1 сенсора в режиме строба; драйвер уже знает об
# этом (ext_leds_mask по умолчанию), нужно лишь разрешить её контролом
# led_mode. Замер: 16 -> 86 средней яркости, воспроизведено дважды.
#
# ВАЖНО: выставлять до старта потока. Сенсор защёлкивает конфигурацию
# GPIO в момент запуска, и то же самое значение, выставленное на уже
# идущем потоке, не даёт ничего.
SUBDEV=$(for x in /sys/class/video4linux/v4l-subdev*; do
             [ "$(cat "$x/name" 2>/dev/null)" = "vd55g 3-0060" ] && echo "/dev/${x##*/}"
         done)
if [ -n "${SUBDEV:-}" ]; then
    v4l2-ctl -d "$SUBDEV" --set-ctrl=led_mode="${IR_LED:-1}" >/dev/null 2>&1 \
        || echo "не удалось включить ИК-подсветку" >&2

    # Частота кадров разменивается на качество картинки.
    #
    # При включённой подсветке драйвер делит потолок экспозиции пополам
    # (limit_flash_duty_cycle), чтобы скважность строба не превысила
    # половину и светодиод не перегрелся. На штатных ~62 кадрах в секунду
    # потолок выходит 898, автоэкспозиция упирается в 875 из них и
    # добирает аналоговым усилением.
    #
    # Кадр длиннее — потолок выше, а скважность та же, светодиод не
    # трогаем. Замер на одной сцене:
    #
    #   62 к/с: экспозиция  875/898,  аналоговое усиление 6
    #   31 к/с: экспозиция 1005/1820, аналоговое усиление 0
    #   21 к/с: экспозиция  968/2770, аналоговое усиление 0
    #
    # На 31 кадре усиление уже нулевое, дальше снижать нечего. Для
    # распознавания лица этого с запасом.
    v4l2-ctl -d "$SUBDEV" --set-ctrl=vertical_blanking="${IR_VBLANK:-3100}" \
        >/dev/null 2>&1 || echo "не удалось задать частоту кадров" >&2
fi

v4l2-ctl -d "${VIDEO:-/dev/video42}" \
  --set-fmt-video=width=$W,height=$H,pixelformat='Y10 ' >/dev/null || exit 1
v4l2-ctl -d "${VIDEO:-/dev/video42}" --get-fmt-video | grep -E "Width|Pixel|Bytes"
