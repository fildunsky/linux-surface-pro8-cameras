#!/bin/bash
# Показать, в каком режиме реально стоит сенсор задней камеры ПРЯМО СЕЙЧАС.
#
# Запускать, пока камера снимает (открыто приложение «Камера», Zoom или
# что угодно ещё) — обесточенный сенсор по I2C не отвечает.
#
# Что означают регистры:
#   0x3811  смещение окна по горизонтали
#   0x3813  смещение окна по вертикали
#   0x3814  прореживание по горизонтали: 0x01 — полное чтение,
#           0x03 — половинное (режимы 2112x...), 0x07 — четверть (1056x784)
#   0x3820  вертикальное прореживание и бит переворота по вертикали
#   0x3821  бит переворота по горизонтали
#
# По таблице режимов драйвера должно быть:
#   4224x3136   0x3811=0x04 0x3813=0x05 0x3814=0x01 0x3820=0xa8
#   2112x1568   0x3811=0x04 0x3813=0x05 0x3814=0x03 0x3820=0xab
#   2112x1188   0x3811=0x08 0x3813=0x03 0x3814=0x03 0x3820=0xab
#   1056x784    0x3811=0x04 0x3813=0x05 0x3814=0x07 0x3820=0xac
# Плюс мои поправки на поворот 180 градусов: 0x3811 +1, 0x3813 -1,
# в 0x3820 подняты биты 4 и 5, в 0x3821 сброшен бит 3.
set -u
cd "$(dirname "$0")"
sudo -v || exit 1
for r in 0x3811 0x3813 0x3814 0x3820 0x3821; do
    printf "  %s = %s\n" "$r" "$(sudo python3 i2c-reg.py 3 0x10 $r | awk '{print $NF}')"
done
