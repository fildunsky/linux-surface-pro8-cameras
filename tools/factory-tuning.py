#!/usr/bin/env python3
"""Собрать файл тюнинга libcamera из заводского Intel .aiqb.

ЗАЧЕМ. Программный ISP libcamera умеет только серый мир (Awb) и матрицу
цветокоррекции (Ccm). Матрицы у него своей нет вовсе, а в .aiqb от Intel лежит
заводская калибровка ровно этого модуля: для каждого источника света — сырые
R/G и B/G нейтральной серой карты и матрица цветокоррекции.

ЧТО КУДА ИДЁТ. Матрицы отдаём как есть: у заводских матриц сумма каждой
строки равна единице, то есть серое на входе остаётся серым на выходе. Это
важнее, чем кажется: программный ISP умножает на матрицу ДО ограничения
сверху, поэтому пересвеченный участок приходит в неё как (1,1,1), и если
суммы строк разные, белое уезжает в цвет. Именно так и вышло, когда баланс
белого был зашит в столбцы матрицы: суммы строк стали 1.14 / 0.31 / 1.45,
зелёный упирался в потолок на 151 из 255, и всё яркое становилось розовым.

Баланс белого поэтому оставляем серому миру, а заводские R/G и B/G идут в
ключи ct: libcamera выбирает матрицу по своей оценке цветовой температуры
(estimateCCT от сырых отношений каналов), и ключи посчитаны той же формулой,
что и в libipa/colours.cpp. Так матрица подбирается под то, что libcamera
реально намерила, а не под паспортную температуру источника.

Использование:
    ./factory-tuning.py <файл.aiqb>                   — показать источники света
    ./factory-tuning.py <файл.aiqb> - [файл.yaml]     — все источники (обычный режим)
    ./factory-tuning.py <файл.aiqb> <CCT> [файл.yaml] — одна матрица, без Awb
"""
import struct, sys

def parse(path):
    b = open(path, 'rb').read()
    f = lambda o: struct.unpack_from('<f', b, o)[0]
    u = lambda o: struct.unpack_from('<I', b, o)[0]

    def isccm(o):
        if o + 36 > len(b): return None
        v = [f(o + 4 * i) for i in range(9)]
        if any(abs(x) > 8 or x != x for x in v): return None
        s = (v[0]+v[1]+v[2], v[3]+v[4]+v[5], v[6]+v[7]+v[8])
        return v if all(abs(x - 1) < 0.02 for x in s) and max(v) > 1.05 else None

    # заголовок источника: u32 ?, float rpg, float bpg, float, float, u32 CCT, затем матрицы
    def hdr(o):
        if o + 24 > len(b): return None
        rpg, bpg = f(o + 4), f(o + 8)
        cct = u(o + 20)
        if not (1000 < cct < 20000 and 0.2 < rpg < 4 and 0.2 < bpg < 4): return None
        return (cct, rpg, bpg) if isccm(o + 24) else None

    for start in range(0, len(b) - 64, 4):          # найти начало таблицы
        if not hdr(start): continue
        recs, o = [], start
        while True:
            h = hdr(o)
            if not h: break
            p = o + 24
            k = 0
            while isccm(p): k += 1; p += 36
            recs.append((*h, [f(o + 24 + 4 * i) for i in range(9)]))
            o = p
        if len(recs) >= 3: return recs
    return []

def estimate_cct(rpg, bpg):
    """Та же оценка, что libcamera делает в ipa/libipa/colours.cpp."""
    m = ((-0.14282, 1.54924, -0.95641),
         (-0.32466, 1.57837, -0.73191),
         (-0.68202, 0.77073,  0.56332))
    rgb = (rpg, 1.0, bpg)
    xyz = [sum(m[i][j] * rgb[j] for j in range(3)) for i in range(3)]
    s = sum(xyz)
    x, y = xyz[0] / s, xyz[1] / s
    n = (x - 0.3320) / (0.1858 - y)
    return round(449 * n ** 3 + 3525 * n ** 2 + 6823.3 * n + 5520.33)


def bake_wb(rec):
    """Зашить баланс белого в столбцы. Ломает белое на пересвете, см. вверху."""
    cct, rpg, bpg, v = rec
    g = [1 / rpg, 1.0, 1 / bpg]
    s = max(g); g = [x / s for x in g]
    return [[v[3 * r + c] * g[c] for c in range(3)] for r in range(3)]


def rows(v):
    return ",\n                 ".join(
        ", ".join(f"{x:8.4f}" for x in v[3 * r:3 * r + 3]) for r in range(3))


def yaml_all(recs, name):
    body = "".join(
        f"        # источник {cct} K, серая карта R/G={rpg:.4f} B/G={bpg:.4f}\n"
        f"        - ct: {estimate_cct(rpg, bpg)}\n          ccm: [ {rows(v)} ]\n"
        for cct, rpg, bpg, v in recs)
    return ("%YAML 1.1\n---\n"
            f"# Заводская калибровка Intel из {name}.\n"
            "# Матрицы отданы как есть (сумма каждой строки = 1). Баланс белого\n"
            "# считает байесовский AWB из libipa по заводской кривой\n"
            "# colourGains ниже. Ключи ct — это не паспортная температура\n"
            "# источника, а то, что выдаёт estimateCCT libcamera от сырых\n"
            "# отношений каналов серой карты; исходная температура в комментарии.\n"
            "# Подробности — tools/factory-tuning.py и NOTES.md.\n"
            "version: 1\nalgorithms:\n"
            + black_level_block(name)
            + awb_block(recs) + "  - Ccm:\n      ccms:\n"
            + body + "  - Adjust:\n  - Agc:\n...\n")


# Пьедестал сенсора в 16-битной шкале, которую ждёт libcamera
# (значение сдвигается на 8 вправо, чтобы получить восьмибитный уровень).
#
# Числа взяты из записи nid=31 заводского .aiqb и подтверждены живьём
# автоопределением libcamera по гистограмме: у ov5693 оно даёт ровно
# 16/255, то есть 64 из 1023 — сходится с заводскими 64.59 DN.
#
# У ov13858 ноль не описка и не лень: пьедестал обнуляет сам драйвер,
# записывая 0 в OV13858_REG_BLC_TARGET (0x4002), и автоопределение на
# живой камере тоже показывает ноль.
BLACK_LEVELS = {
    # 31.08.2026, вечер. Здесь стоит ноль, хотя пьедестал у ov5693 реально
    # есть (64.59 DN из 1023 по заводским данным, и автоопределение
    # libcamera на живой камере даёт ровно столько же). Причина: вся
    # заводская калибровка снята с пьедесталом ВНУТРИ — и отношения серой
    # карты, и матрицы цветокоррекции. Стоит его вычесть, как матрицы
    # перестают соответствовать данным и кадр уходит в зелень; проверено и
    # с байесовским AWB, и с серым миром, картина одна.
    #
    # При этом сам по себе пьедестал очень нужен: с ним чёрный становится
    # чёрным (нижний процент яркости 63 -> 0), контраст растёт на 40 %, а
    # насыщенность почти вдвое. Это ровно та блёклость, на которую жалоба.
    #
    # Чтобы получить и то и другое, надо привести калибровку к единицам без
    # пьедестала: либо пересчитать матрицы, либо вычитать пьедестал после
    # матрицы, а не до. Это работа на подумать, не на вечер.
    "OV5693": (0, "пьедестал есть (64.59 DN), но вычитать его нельзя, пока "
                  "матрицы сняты с ним внутри — см. комментарий в коде"),
    "OV13858": (0, "пьедестал обнуляет драйвер записью в 0x4002, "
                   "автоопределение на живой камере тоже даёт ноль"),
}


def black_level_block(name):
    for key, (level, why) in BLACK_LEVELS.items():
        if key in name.upper():
            return (f"  # {why}.\n"
                    f"  - BlackLevel:\n      blackLevel: {level}\n")
    # Незнакомый сенсор: пусть libcamera определит пьедестал сама по
    # гистограмме, это лучше, чем поставить наугад ноль.
    print(f"  пьедестал для {name} неизвестен, отдан на автоопределение",
          file=sys.stderr)
    return "  - BlackLevel:\n"


def monotonic(pts):
    """Оставить на кривой только строго монотонный ход обоих каналов.

    AwbBayes строит обратные функции ct->R и ct->B (ctR_.inverse()), а Pwl
    умеет обращать только монотонную ломаную: точки, идущие против хода,
    он молча выбрасывает и лишь помечает результат как «не настоящая
    обратная». Лучше выкинуть их здесь и вслух, чем полагаться на это
    молчание.

    В заводских данных фронталки такая точка одна: два источника с
    паспортными 2900 и 2901 K дают разную цветность (это разные лампы с
    одинаковой цветовой температурой), и по оценке estimateCCT они
    расходятся на 2865 и 2994 K, причём второй идёт против общего хода
    синего канала. Матриц цветокоррекции это не касается — там остаются
    все источники, интерполяция матриц монотонности не требует.
    """
    kept = []
    for pt in pts:
        if not kept:
            kept.append(pt)
            continue
        ct, r, b = pt
        pct, pr, pb = kept[-1]
        # AwbBayes хранит на кривой 1/усиление, поэтому монотонность
        # проверяем по ним: 1/R убывает с ростом ct, 1/B растёт, то есть
        # само усиление красного растёт, а синего падает.
        if r > pr and b < pb:
            kept.append(pt)
        else:
            print(f"  кривая AWB: точка ct={ct} выброшена, идёт против хода",
                  file=sys.stderr)
    return kept


def awb_block(recs):
    """Секция Awb с заводской кривой источников света.

    Отношения каналов серой карты, снятые на заводе на этом экземпляре
    оптики, — это и есть эталонный баланс белого: усиление, которое надо
    приложить, чтобы серая карта стала серой. Раньше они шли только на
    вычисление ключа ct, а сам баланс считал серый мир.

    Байесовский AWB из libipa (patches/libcamera/softisp-awb-use-libipa-bayes)
    берёт эту кривую и выбирает на ней наиболее правдоподобный источник
    света вместо того, чтобы вслепую тянуть среднее по кадру к серому.
    Ключи ct те же, что у матриц, — иначе кривая и матрицы разъедутся.

    priors — априорное распределение вероятности источников света по
    освещённости. Заводских данных на этот счёт в .aiqb нет, поэтому
    распределение взято равномерным: это честно означает «никакой источник
    заранее не предпочтителен», и вся работа достаётся правдоподобию по
    самому кадру. Освещённость софтовый ISP не считает, алгоритм всегда
    получает одно и то же значение, так что вторая точка по lux смысла не
    имеет.
    """
    pts = monotonic(sorted((estimate_cct(rpg, bpg), 1 / rpg, 1 / bpg)
                           for _, rpg, bpg, _ in recs))
    gains = "".join(
        f"        - ct: {ct}\n          gains: [ {r:.4f}, {b:.4f} ]\n"
        for ct, r, b in pts)
    cts = ", ".join(str(ct) for ct, _, _ in pts)
    probs = ", ".join("1.0" for _ in pts)
    return ("  - Awb:\n"
            "      colourGains:\n" + gains +
            "      priors:\n"
            "        - lux: 0\n"
            f"          ct: [ {cts} ]\n"
            f"          probability: [ {probs} ]\n"
            "      AwbMode:\n"
            # ключ — имя элемента перечисления из control_ids_core.yaml,
            # то есть AwbAuto, а не auto: parseModeConfigs сверяется с
            # controls::AwbModeNameValueMap и незнакомые имена молча
            # пропускает, из-за чего режимов не остаётся вовсе и весь
            # разбор тюнинга падает
            "        AwbAuto:\n"
            f"          lo: {pts[0][0]}\n"
            f"          hi: {pts[-1][0]}\n")


def yaml_one(M, cct):
    body = ",\n                 ".join(", ".join(f"{x:8.4f}" for x in r) for r in M)
    return ("%YAML 1.1\n---\n"
            f"# Заводская калибровка Intel: источник света {cct} K.\n"
            "# Awb отсутствует, баланс белого зашит в столбцы матрицы. Режим\n"
            "# оставлен для сравнения: белое на пересвете уходит в розовый.\n"
            "version: 1\nalgorithms:\n  - BlackLevel:\n  - Ccm:\n      ccms:\n"
            f"        - ct: {cct}\n          ccm: [ " + body + " ]\n  - Adjust:\n  - Agc:\n...\n")


if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    recs = parse(sys.argv[1])
    if not recs: sys.exit("таблица источников света не найдена")
    if len(sys.argv) == 2:
        print(f"{'CCT':>6} {'сырой R/G':>10} {'сырой B/G':>10} {'ключ ct':>8}   баланс белого")
        for cct, rpg, bpg, _ in recs:
            print(f"{cct:6d} {rpg:10.4f} {bpg:10.4f} {estimate_cct(rpg, bpg):8d}"
                  f"   gR={1/rpg:.3f} gB={1/bpg:.3f}")
        sys.exit()
    if sys.argv[2] == '-':
        out = yaml_all(recs, sys.argv[1].split('/')[-1])
    else:
        rec = min(recs, key=lambda r: abs(r[0] - int(sys.argv[2])))
        out = yaml_one(bake_wb(rec), rec[0])
    if len(sys.argv) > 3: open(sys.argv[3], 'w').write(out)
    else: sys.stdout.write(out)
